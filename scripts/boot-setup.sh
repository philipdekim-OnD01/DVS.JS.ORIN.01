#!/usr/bin/env bash
# nrv-dvs-jetson boot setup (path B-2: rootfs modules + depmod override + DT overlay).
#
#   scripts/boot-setup.sh check       read-only preflight (no root needed)
#   sudo scripts/boot-setup.sh install [--dry-run]
#                                     install build/ artifacts, add/refresh the
#                                     "nrv-dvs" extlinux entry and make it DEFAULT
#   scripts/boot-setup.sh status      after reboot: is the overlay applied and are
#                                     the loaded modules the ones in build/?
#   sudo scripts/boot-setup.sh uninstall
#                                     remove everything install added, restore DEFAULT
#
# What install changes (and nothing else):
#   /lib/modules/$K/updates/nrv/nrv_dvs.ko                     new file
#   /lib/modules/$K/updates/nrv/tegra-camera.ko                removed if an older
#                                                              install left one
#   /etc/depmod.d/nrv-dvs.conf                                 override -> updates/nrv
#   /lib/modules/$K/modules.*                                  regenerated by depmod
#   /boot/nrv-dvs/cam1.dtbo, /boot/nrv-dvs/install.state       new files
#   /boot/nrv-dvs/backup/extlinux.conf.<timestamp>             backup
#   /boot/extlinux/extlinux.conf                               "nrv-dvs" entry + DEFAULT
# The NVIDIA camera stack stays stock (the sensor sends RAW8 0x2A). NVIDIA-owned
# files (tegra-camera.ko, /boot/initrd, /boot/dtb/*) are never modified, and
# nothing is ever added to /boot/dtb (NVIDIA's dtbs postinst and Jetson-IO
# assume a single .dtb there).
#
# This script NEVER runs rmmod/insmod/modprobe: unloading the NVIDIA camera stack
# at runtime hard-hung the board (2026-10-12). New modules take effect on reboot.
set -euo pipefail

ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
# shellcheck source=../bsp/r39.2.1/manifest.env
source "$ROOT/bsp/r39.2.1/manifest.env"
K=$KERNEL_RELEASE
BUILD=$ROOT/build
KO_DVS=$BUILD/nrv_dvs.ko
DTBO=$BUILD/cam1.dtbo
MODSUB=updates/nrv
MODDIR=/lib/modules/$K/$MODSUB
DEPMOD_CONF=/etc/depmod.d/nrv-dvs.conf
BOOTDIR=/boot/nrv-dvs
STATE=$BOOTDIR/install.state
EXTLINUX=/boot/extlinux/extlinux.conf
LABEL=nrv-dvs
DT=/sys/firmware/devicetree/base
DRY=0

log()  { printf '[boot-setup] %s\n' "$*" >&2; }
warn() { printf '[boot-setup] WARNING: %s\n' "$*" >&2; }
die()  { printf '[boot-setup] ERROR: %s\n' "$*" >&2; exit 1; }
run()  { if ((DRY)); then printf '[dry-run] %s\n' "$*" >&2; else "$@"; fi; }

# Temp file next to extlinux.conf so the final mv is atomic (dry-run: $TMPDIR).
mk_extlinux_tmp() { if ((DRY)); then mktemp; else mktemp /boot/extlinux/.extlinux.conf.XXXXXX; fi; }

need_root() { ((DRY)) || [[ $EUID -eq 0 ]] || die "run with sudo"; }

# Base DTB = the single /boot/dtb/kernel_*.dtb whose model matches the running board
# (same rule as Jetson-IO). The file name is per board SKU, not per L4T version;
# the nvidia-l4t-kernel-dtbs postinst refreshes it in place on BSP updates.
find_base_dtb() {
  local model f hits=()
  model=$(tr -d '\0' < "$DT/model")
  for f in /boot/dtb/kernel_*.dtb; do
    [[ -f $f ]] || continue
    [[ $(fdtget -t s "$f" / model 2>/dev/null) == "$model" ]] && hits+=("$f")
  done
  ((${#hits[@]} == 1)) || die "expected exactly 1 base DTB for model '$model' in /boot/dtb/kernel_*.dtb, found ${#hits[@]}: ${hits[*]:-none}"
  printf '%s\n' "${hits[0]}"
}

primary_append() {
  python3 - "$EXTLINUX" <<'PY'
import re, sys
label = None
for line in open(sys.argv[1]):
    s = line.strip()
    if s.startswith('#'): continue
    m = re.match(r'LABEL\s+(\S+)', s)
    if m: label = m.group(1); continue
    if label == 'primary' and s.startswith('APPEND '):
        print(s[len('APPEND '):]); sys.exit(0)
sys.exit(1)
PY
}

cmd_check() {
  local c base tmp ok=1
  for c in fdtget fdtoverlay modinfo depmod python3 sha256sum readelf; do
    command -v "$c" >/dev/null || die "required command not found: $c"
  done
  [[ $(uname -r) == "$K" ]] || die "running kernel $(uname -r) != pinned $K"
  for c in "$KO_DVS" "$DTBO"; do [[ -f $c ]] || die "missing $c (run ./build.sh all)"; done
  [[ $(modinfo -F vermagic "$KO_DVS" | awk '{print $1}') == "$K" ]] || die "vermagic mismatch: $KO_DVS"
  log "kernel $K, build artifacts present, vermagic OK"

  base=$(find_base_dtb); log "base DTB: $base"
  tmp=$(mktemp -d)
  fdtoverlay -i "$base" -o "$tmp/merged.dtb" "$DTBO" || { rm -rf "$tmp"; die "cam1.dtbo does not apply to $base"; }
  local node; node=$(fdtget -l "$tmp/merged.dtb" /bus@0/i2c@3180000 2>/dev/null | grep '^nrv_dvs@' | head -1)
  [[ -n $node ]] || die "merged DT has no nrv_dvs node under /bus@0/i2c@3180000"
  rm -rf "$tmp"
  log "cam1.dtbo applies offline to base DTB; $node present"

  primary_append >/dev/null || die "no 'primary' entry with APPEND in $EXTLINUX"
  log "extlinux: primary entry found (APPEND will be copied); DEFAULT is '$(awk '$1=="DEFAULT"{print $2}' "$EXTLINUX")'"

  # Informational findings.
  local n; n=$(find /boot/dtb -maxdepth 1 -name '*.dtb' | wc -l)
  ((n == 1)) || warn "/boot/dtb holds $n .dtb files; NVIDIA's kernel-dtbs postinst ('ls *.dtb') and Jetson-IO assume one. Not caused by this script."
  [[ -e /lib/modules/$K/extra/nrv_dvs.ko ]] && warn "stale /lib/modules/$K/extra/nrv_dvs.ko (not package-owned) exists; the depmod override makes updates/nrv win, file left untouched"
  [[ -e $MODDIR/tegra-camera.ko ]] && log "$MODDIR/tegra-camera.ko from an older install will be removed by install (stock tegra-camera is used)"
  [[ -e /boot/cam1.dtbo ]] && warn "/boot/cam1.dtbo exists (manual copy?); install uses $BOOTDIR/cam1.dtbo, the old file is left untouched"
  grep -Eq "^\s*LABEL\s+$LABEL\s*$" "$EXTLINUX" && log "existing '$LABEL' entry will be replaced by install"
  [[ -f $STATE ]] && log "already installed: $(grep -E '^(installed_at|ko_dvs_sha256)=' "$STATE" | tr '\n' ' ')"
  ((ok)) && log "check OK"
}

write_extlinux() { # write_extlinux <base_dtb> <append> <new_default> <outfile>
  python3 - "$EXTLINUX" "$LABEL" "$1" "$BOOTDIR/cam1.dtbo" "$2" "$3" "$4" <<'PY'
import re, sys
src, label, fdt, dtbo, append, default, out = sys.argv[1:]
lines = open(src).read().splitlines()
res, skip = [], False
for line in lines:
    m = re.match(r'\s*LABEL\s+(\S+)\s*$', line)
    if m:
        skip = (m.group(1) == label)
        if skip:
            continue
    elif skip and re.match(r'\s+[A-Z]', line):
        continue          # indented directive of the removed entry
    else:
        skip = False      # blank/comment/other line ends the entry
    if skip:
        continue
    if re.match(r'\s*DEFAULT\s+\S+', line):
        line = 'DEFAULT ' + default
    if res and not res[-1].strip() and not line.strip():
        continue
    res.append(line)
while res and not res[-1].strip():
    res.pop()
res += ['', f'LABEL {label}',
        '      MENU LABEL NRV DVS camera (nrv-dvs-jetson)',
        '      LINUX /boot/Image',
        f'      FDT {fdt}',
        '      INITRD /boot/initrd',
        f'      OVERLAYS {dtbo}',
        f'      APPEND {append}', '']
if not any(re.match(r'\s*DEFAULT\s+', l) for l in res):
    sys.exit('no DEFAULT line in extlinux.conf')
open(out, 'w').write('\n'.join(res))
PY
}

cmd_install() {
  need_root
  cmd_check
  local base append prev ts tmp
  base=$(find_base_dtb); append=$(primary_append)
  prev=$(awk '$1=="DEFAULT"{print $2}' "$EXTLINUX")
  # Keep the DEFAULT that was active before the first install, for uninstall.
  if [[ -f $STATE ]]; then prev=$(sed -n 's/^previous_default=//p' "$STATE"); fi
  [[ -z $prev || $prev == "$LABEL" ]] && prev=primary
  ts=$(date +%Y%m%d-%H%M%S)

  log "modules -> $MODDIR"
  run install -d -m 755 "$MODDIR"
  run install -m 644 "$KO_DVS" "$MODDIR/"
  # A patched tegra-camera.ko from an older install would still win over the
  # stock one (updates/ is searched first).
  run rm -f "$MODDIR/tegra-camera.ko"
  log "depmod override -> $DEPMOD_CONF"
  if ((DRY)); then
    printf '[dry-run] write %s:\n  override nrv_dvs %s %s\n' "$DEPMOD_CONF" "$K" "$MODSUB" >&2
  else
    printf '# installed by nrv-dvs-jetson scripts/boot-setup.sh\noverride nrv_dvs %s %s\n' \
      "$K" "$MODSUB" > "$DEPMOD_CONF"
  fi
  run depmod -a "$K"
  if ! ((DRY)); then
    [[ $(modinfo -n -k "$K" nrv_dvs) == "$MODDIR/nrv_dvs.ko" ]] || die "depmod did not select $MODDIR/nrv_dvs.ko"
    [[ $(modinfo -n -k "$K" tegra_camera) != "$MODDIR/"* ]] || die "depmod still selects a tegra-camera.ko under $MODDIR"
    log "modules.dep now resolves nrv_dvs to $MODDIR, tegra_camera to $(modinfo -n -k "$K" tegra_camera)"
  fi

  run install -d -m 755 "$BOOTDIR/backup"
  run cp -p "$EXTLINUX" "$BOOTDIR/backup/extlinux.conf.$ts"
  run install -m 644 "$DTBO" "$BOOTDIR/cam1.dtbo"

  tmp=$(mk_extlinux_tmp)
  write_extlinux "$base" "$append" "$LABEL" "$tmp"
  if ((DRY)); then
    log "extlinux.conf diff (not applied):"; diff -u "$EXTLINUX" "$tmp" >&2 || true; rm -f "$tmp"
  else
    chmod 644 "$tmp"; mv -f "$tmp" "$EXTLINUX"
    {
      echo "installed_at=$ts"
      echo "kernel=$K"
      echo "previous_default=$prev"
      echo "base_dtb=$base"
      echo "extlinux_backup=$BOOTDIR/backup/extlinux.conf.$ts"
      echo "ko_dvs_sha256=$(sha256sum < "$KO_DVS" | cut -d' ' -f1)"
      echo "dtbo_sha256=$(sha256sum < "$DTBO" | cut -d' ' -f1)"
      echo "git_commit=$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
    } > "$STATE"
    log "installed. DEFAULT=$LABEL (previous: $prev). Reboot to activate, then run: scripts/boot-setup.sh status"
  fi
}

# GNU build-id: identifies the exact .ko binary (srcversion is not exported here).
file_build_id()   { readelf -n "$1" 2>/dev/null | awk '/Build ID:/{print $3; exit}'; }
loaded_build_id() { od -An -v -tx1 "/sys/module/$1/notes/.note.gnu.build-id" 2>/dev/null | tr -d ' \n' | tail -c 40; }

cmd_status() {
  local node m want have fail=0
  log "DEFAULT: $(awk '$1=="DEFAULT"{print $2}' "$EXTLINUX"); kernel cmdline boot entry is not exposed, checking effects instead"
  node=$(ls -d "$DT"/bus@0/i2c@3180000/nrv_dvs@* 2>/dev/null | head -1 || true)
  if [[ -n $node ]]; then
    log "DT overlay: applied ($(basename "$node"))"
  else
    warn "DT overlay: NOT applied (no nrv_dvs node)"; fail=1
  fi
  if [[ ! -d /sys/module/nrv_dvs ]]; then
    warn "nrv_dvs: not loaded"; fail=1
  else
    have=$(loaded_build_id nrv_dvs); want=$(file_build_id "$KO_DVS")
    if [[ -n $have && $have == "$want" ]]; then log "nrv_dvs: loaded = build/ (build-id ${have:0:12})"
    else warn "nrv_dvs: loaded build-id ${have:0:12} != build/ ${want:0:12} (older module)"; fail=1; fi
  fi
  m=$(modinfo -n tegra_camera 2>/dev/null || true)
  have=$(loaded_build_id tegra_camera); want=$(file_build_id "$m")
  if [[ $m == "$MODDIR/"* ]]; then warn "tegra_camera resolves to $m (not stock); run install again"; fail=1
  elif [[ -n $have && $have == "$want" ]]; then log "tegra_camera: loaded = stock $m"
  else warn "tegra_camera: loaded build-id ${have:0:12} != $m ${want:0:12} (reboot pending?)"; fail=1; fi
  if [[ -d /sys/module/nrv_dvs/parameters ]]; then
    # The current nrv_dvs.ko has no module parameters; any listed here mean an older module.
    log "nrv_dvs params (expected none): $(ls /sys/module/nrv_dvs/parameters | tr '\n' ' ')"
  elif [[ -d /sys/module/nrv_dvs ]]; then
    log "nrv_dvs params: none (settings via V4L2 control nrv_register_writes)"
  fi
  if compgen -G '/dev/video*' >/dev/null; then log "video nodes: $(echo /dev/video*)"; else warn "no /dev/video*"; fail=1; fi
  ((fail)) && { warn "status: NOT ready"; return 1; }
  log "status: ready (receive test: ./dvs start)"
}

cmd_uninstall() {
  need_root
  local prev=primary tmp
  [[ -f $STATE ]] && prev=$(sed -n 's/^previous_default=//p' "$STATE")
  [[ -z $prev || $prev == "$LABEL" ]] && prev=primary
  if grep -Eq "^\s*LABEL\s+$LABEL\s*$" "$EXTLINUX"; then
    run install -d -m 755 "$BOOTDIR/backup"
    run cp -p "$EXTLINUX" "$BOOTDIR/backup/extlinux.conf.$(date +%Y%m%d-%H%M%S)"
    tmp=$(mk_extlinux_tmp)
    python3 - "$EXTLINUX" "$LABEL" "$prev" "$tmp" <<'PY'
import re, sys
src, label, default, out = sys.argv[1:]
res, skip = [], False
for line in open(src).read().splitlines():
    m = re.match(r'\s*LABEL\s+(\S+)\s*$', line)
    if m:
        skip = (m.group(1) == label)
        if skip: continue
    elif skip and re.match(r'\s+[A-Z]', line):
        continue
    else:
        skip = False
    if skip: continue
    if res and not res[-1].strip() and not line.strip(): continue
    if re.match(r'\s*DEFAULT\s+\S+', line): line = 'DEFAULT ' + default
    res.append(line)
while res and not res[-1].strip(): res.pop()
open(out, 'w').write('\n'.join(res) + '\n')
PY
    if ((DRY)); then diff -u "$EXTLINUX" "$tmp" >&2 || true; rm -f "$tmp"
    else chmod 644 "$tmp"; mv -f "$tmp" "$EXTLINUX"; fi
  fi
  run rm -f "$MODDIR/tegra-camera.ko" "$MODDIR/nrv_dvs.ko" "$DEPMOD_CONF"
  [[ -d $MODDIR ]] && run rmdir --ignore-fail-on-non-empty "$MODDIR"
  run depmod -a "$K"
  run rm -f "$BOOTDIR/cam1.dtbo" "$STATE"
  log "uninstalled (DEFAULT=$prev, backups kept in $BOOTDIR/backup). Reboot to return to the stock modules."
}

main() {
  local cmd=${1:-}; shift || true
  [[ ${1:-} == --dry-run ]] && DRY=1
  case $cmd in
    check) cmd_check ;;
    install) cmd_install ;;
    status) cmd_status ;;
    uninstall) cmd_uninstall ;;
    *) sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 2 ;;
  esac
}
main "$@"
